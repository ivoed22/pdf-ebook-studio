import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "docs/gpt-agent/pdf-ebook-studio-gpt-knowledge.md");
const sources = [
  "README.md",
  "docs/02-app-requirements.md",
  "docs/03-markdown-input-format.md",
  "docs/04-image-naming-rules.md",
  "docs/05-acceptance-criteria-test-plan.md",
  "docs/08-agent-pack-import.md",
  "docs/schemas/project-schema.json",
  "src/data/templates/starter-template-pack-expanded-v2.json",
  "src/data/themes/themes.ts",
  "src/data/samples/interior-magazine-sample.md",
  "src/data/samples/recipe-ebook-sample.md",
];

const sections = await Promise.all(
  sources.map(async (source) => {
    const content = await readFile(resolve(root, source), "utf8");
    if (source.endsWith(".md")) return `## Source: ${source}\n\n${content.trim()}`;
    const language = source.endsWith(".json") ? "json" : "ts";
    return `## Source: ${source}\n\n\`\`\`${language}\n${content.trim()}\n\`\`\``;
  }),
);

const generated = `# PDF Ebook Studio GPT Knowledge\n\nGenerated from the current repository. Do not edit this file manually; run \`npm run generate:gpt-knowledge\`.\n\n${sections.join("\n\n---\n\n")}\n`;

await mkdir(dirname(output), { recursive: true });
await writeFile(output, generated, "utf8");
console.log(`Generated ${output} from ${sources.length} sources.`);
